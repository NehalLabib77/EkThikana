  foreground artwork is intentionally inset by ~6dp on every side.

  The foreground is the brand mark itself, rendered in pure white
  (#FFFFFFFF) so it reads against the brand-purple background coming
  from @color/ic_launcher_background and recolours correctly on the
  Android 13 themed-icons feature (which tints the background from
  the user's wallpaper palette).

