      * a soft rounded-square plate (corner radius ~16dp in the
        108dp viewport), and
      * a chunky stylised "G" centred inside it.

  Vector form is intentional: a vector foreground keeps the APK small
  and renders crisply at any launcher size; the raster master artwork
  in flutter_app/assets/branding/gochano1.png is used for the legacy
  mipmap-*/ic_launcher.png raster fallback (regenerated by
  tool/regen_launcher_icon.py).

  Master artwork: flutter_app/assets/branding/gochano1.png
